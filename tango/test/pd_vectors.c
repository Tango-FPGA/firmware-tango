/*
 * pd_vectors.c -- writes the test vectors for sys-tango's tango_pad_decode.v unit bench (sys-tango sim/pads/).
 *
 *   ./pd_vectors > sys-tango sim/pads/pad_vectors.txt      (the file is committed in sys-tango, the bench needs no C)
 *
 * The C reference pd_eval() (tango_paddec.c) is the golden: every REPORT line carries the raw word it must produce, and whether the report
 * must be accepted at all (header checks). Tables: the built-in DualShock 4 and XInput, tables built from the synthetic descriptors of
 * pad_fixtures.h, and random tables that exercise every comparison, every shift / width / byte, bias, and reports that straddle the
 * 16-byte window. Deterministic (fixed seed).
 *
 * Format (one item per line):
 *   TABLE <name> <mode> <rid_en> <rid_val> <min_len> <count>
 *   ENT <10 hex digits>                   (the 36-bit entry word, count lines)
 *   REPORT <len> <32 hex digits = bytes 0..15> <accepted 0/1> <raw, 8 hex digits>
 *   END
 */
#include <stdio.h>
#include <string.h>
#include <stdint.h>
#include "../tango_hidparse.h"
#include "../tango_paddb.h"
#include "../tango_paddec.h"
#include "pad_fixtures.h"

static uint32_t rng_s = 0xC0FFEEu;
static uint32_t rnd(void) { rng_s ^= rng_s << 13; rng_s ^= rng_s >> 17; rng_s ^= rng_s << 5; return rng_s; }

static long nreports = 0, ntables = 0;

static void emit_table_header(const char *name, const pd_table_t *t)
{
    printf("TABLE %s %d %d %d %d %d\n", name, t->mode, t->rid_en, t->rid_val, t->min_len, t->count);
    for (int i = 0; i < t->count; i++) printf("ENT %010llx\n", (unsigned long long)pd_ent_pack(&t->e[i]));
    ntables++;
}

static void emit_report(const pd_table_t *t, const uint8_t *r, int len)
{
    uint32_t raw = 0;
    int acc = pd_eval(t, r, len, &raw);
    uint8_t b[16] = { 0 };
    for (int i = 0; i < 16 && i < len; i++) b[i] = r[i];
    /* bytes the host holds beyond the payload are stale data in the real design: put noise there so the engine's zero fill is tested */
    for (int i = len; i < 16; i++) b[i] = (uint8_t)rnd();
    printf("REPORT %d ", len);
    for (int i = 0; i < 16; i++) printf("%02x", b[i]);
    printf(" %d %08x\n", acc, acc ? raw : 0u);
    nreports++;
}

static void emit_table(const char *name, const pd_table_t *t, int nrand, int minlen_hint)
{
    emit_table_header(name, t);
    for (int k = 0; k < nrand; k++) {
        uint8_t r[24]; for (int i = 0; i < 24; i++) r[i] = (uint8_t)rnd();
        int len = (k % 7 == 0) ? (int)(rnd() % 20) : (minlen_hint > 0 ? minlen_hint + (int)(rnd() % 8) : 8 + (int)(rnd() % 12));
        if (t->rid_en && (k % 3)) r[0] = t->rid_val;                      /* mostly the right id */
        if (k % 5 == 0) memset(r + 1, 0, 15);                             /* idle-ish */
        if (k % 11 == 0) memset(r + 1, 0xFF, 15);
        emit_report(t, r, len > 24 ? 24 : len);
    }
    printf("END\n");
}

static void random_table(pd_table_t *t, int n)
{
    memset(t, 0, sizeof *t);
    t->mode = PDM_TABLE; t->rid_en = rnd() & 1; t->rid_val = (uint8_t)(rnd() % 4); t->min_len = (uint8_t)(rnd() % 12); t->count = (uint8_t)n;
    for (int i = 0; i < n; i++) {
        pd_ent_t *e = &t->e[i];
        e->out = (uint8_t)(rnd() % 32); e->cmp = (uint8_t)(rnd() % 6);
        e->byte = (uint8_t)(rnd() % 16); e->shift = (uint8_t)(rnd() % 8); e->widthm1 = (uint8_t)(rnd() % 16);
        e->bias = (uint8_t)(rnd() & 1);
        switch (rnd() % 4) {
        case 0: e->thr = (uint16_t)rnd(); break;
        case 1: e->thr = (uint16_t)(rnd() % 256); break;
        case 2: e->thr = (uint16_t)((1u << (e->widthm1 + 1 > 16 ? 16 : e->widthm1 + 1)) / 2); break;     /* mid range */
        default: e->thr = (uint16_t)(((rnd() % 16) << 8) | (rnd() & 0xFF)); break;                       /* hat style */
        }
        if (e->cmp == PDC_NZ || e->cmp == PDC_Z) e->widthm1 = (uint8_t)(rnd() % 3 == 0 ? rnd() % 16 : 0);
    }
}

int main(void)
{
    static pd_table_t t; static hp_layout_t L; pd_build_info_t info; sdl_map_t m;
    printf("# pad_vectors.txt -- generated by menu-tango bl616/tango/test/pd_vectors.c from the C reference pd_eval (tango_paddec.c). Do not edit.\n");

    pd_builtin_ds4(&t);           emit_table("ds4", &t, 600, 8);
    pd_builtin_xinput(&t);        emit_table("xinput", &t, 600, 20);
    pd_quiet(&t);                 emit_table("quiet", &t, 20, 0);
    memset(&t, 0, sizeof t); t.mode = PDM_TABLE; emit_table("empty", &t, 30, 0);

    hp_parse(D_DS4, sizeof D_DS4, &L);
    sdl_parse_line("030000004c050000cc09000000000000,PS4 Controller,a:b1,b:b2,back:b8,dpdown:h0.4,dpleft:h0.8,dpright:h0.2,dpup:h0.1,guide:b12,leftshoulder:b4,"
                   "leftstick:b10,lefttrigger:a3,leftx:a0,lefty:a1,rightshoulder:b5,rightstick:b11,righttrigger:a4,rightx:a2,righty:a5,start:b9,x:b0,y:b3,platform:Linux,", &m);
    pd_from_sdl(&L, &m, &t, &info);          emit_table("ds4_from_descriptor", &t, 600, 10);

    hp_parse(D_SNES12, sizeof D_SNES12, &L);   pd_from_layout(&L, &t, &info); emit_table("snes12", &t, 400, 4);
    hp_parse(D_HAT12, sizeof D_HAT12, &L);     pd_from_layout(&L, &t, &info); emit_table("hat12", &t, 400, 6);
    hp_parse(D_TWOID, sizeof D_TWOID, &L);     pd_from_layout(&L, &t, &info); emit_table("twoid", &t, 400, 4);
    hp_parse(D_HAT4, sizeof D_HAT4, &L);       pd_from_layout(&L, &t, &info); emit_table("hat4", &t, 300, 2);
    hp_parse(D_XBOXHID, sizeof D_XBOXHID, &L);
    sdl_parse_line("030000005e040000ff02000000000000,Test Xbox HID,a:b0,b:b1,x:b2,y:b3,back:b6,start:b7,leftshoulder:b4,rightshoulder:b5,leftstick:b8,rightstick:b9,"
                   "dpup:h0.1,dpdown:h0.4,dpleft:h0.8,dpright:h0.2,leftx:a0,lefty:a1,rightx:a3,righty:a4,lefttrigger:a2,righttrigger:a5,platform:Linux,", &m);
    pd_from_sdl(&L, &m, &t, &info);          emit_table("xboxhid", &t, 800, 14);

    /* random tables: sizes 1, 2, 3, 7, 31, 63, 64 and a spread */
    static const int SZ[] = { 1, 2, 3, 5, 8, 13, 24, 31, 40, 55, 63, 64 };
    for (unsigned k = 0; k < sizeof SZ / sizeof SZ[0]; k++) {
        char nm[32];
        for (int rep = 0; rep < 3; rep++) {
            random_table(&t, SZ[k]);
            snprintf(nm, sizeof nm, "random_%d_%d", SZ[k], rep);
            emit_table(nm, &t, 150, 0);
        }
    }
    fprintf(stderr, "%ld tables, %ld reports\n", ntables, nreports);
    return 0;
}
